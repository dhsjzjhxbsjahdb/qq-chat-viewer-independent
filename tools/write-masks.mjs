#!/usr/bin/env node
// Write masks.js for the viewer from privacy-report.json: which message-id ranges are masked and why.
// Only ids, never text. Every masked line reads "*******"; the viewer needs the kind to label it:
//   sequel   – 魔女2 conversations and whole redacted days (folded for good)
//   business – private commercial details (only those lines are sealed)
// Run after any redaction change; tools/check-privacy.mjs verifies masks.js matches the report.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function masksFor(report) {
  const s = report.sensitive_review;
  return {
    mask: report.sequel_review.mask,
    sequel: [...report.sequel_review.ranges, ...(s.date_ranges || [])].sort((a, b) => a[0] - b[0]),
    business: s.business_ranges || [],
  };
}

export const masksSource = masks => `// Generated by tools/write-masks.mjs from privacy-report.json — message-id ranges only, no text.\nwindow.__MASKS__ = ${JSON.stringify(masks)};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const masks = masksFor(JSON.parse(readFileSync(resolve(ROOT, 'privacy-report.json'), 'utf8')));
  writeFileSync(resolve(ROOT, 'masks.js'), masksSource(masks));
  console.log(JSON.stringify({ ok: true, sequel_ranges: masks.sequel.length, business_ranges: masks.business.length }));
}
