#!/usr/bin/env node
// Local annotation editor for the chat viewer.
//
//   node tools/annotate.mjs            → http://127.0.0.1:8780/edit
//   PORT=9000 node tools/annotate.mjs
//
// Serves the site from the repository root and adds two things that the published (static) site
// does not have: the editor page at /edit, and POST api/notes, which rewrites notes.js.
// Publish annotations by committing notes.js.
import { createServer } from 'node:http';
import { readFile, writeFile, rename, stat } from 'node:fs/promises';
import { join, normalize, extname, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const NOTES = join(ROOT, 'notes.js');
const PORT = +process.env.PORT || 8780;
const HOST = '127.0.0.1';
const MAX_BODY = 4 << 20;
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8', '.svg': 'image/svg+xml',
  '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp', '.ico': 'image/x-icon',
};

function send(res, code, body, type = 'text/plain; charset=utf-8') {
  // explicit length: some reverse proxies (e.g. the Team preview) drop chunked responses to POST requests
  const buf = Buffer.isBuffer(body) ? body : Buffer.from(String(body), 'utf8');
  res.writeHead(code, { 'Content-Type': type, 'Content-Length': buf.length, 'Cache-Control': 'no-store', 'X-Robots-Tag': 'noindex' });
  res.end(buf);
}

// The editor page is the normal viewer plus the editor script; it never exists as a file.
async function editPage() {
  let html = await readFile(join(ROOT, 'index.html'), 'utf8');
  const app = /<script src="app\.js[^"]*"><\/script>/;
  if (!app.test(html)) throw new Error('index.html: app.js script tag not found');
  html = html.replace(app, m => `${m}\n<link rel="stylesheet" href="tools/editor.css">\n<script src="tools/editor.js"></script>`);
  return html.replace('<title>', '<title>编辑批注 · ');
}

function cleanNotes(input) {
  if (!Array.isArray(input)) throw new Error('notes must be an array');
  const seen = new Set(), out = [];
  for (const n of input) {
    if (!n || !Number.isInteger(n.i) || n.i < 0) throw new Error('bad message id');
    if (typeof n.n !== 'string' || n.n.length > 20000) throw new Error('bad note text');
    const text = n.n.replace(/\r\n?/g, '\n').trim();
    if (!text || seen.has(n.i)) continue;
    seen.add(n.i);
    out.push({ i: n.i, n: text, u: typeof n.u === 'string' ? n.u.slice(0, 40) : new Date().toISOString() });
  }
  return out.sort((a, b) => a.i - b.i);
}

async function saveNotes(list) {
  const body = '// 批注 — generated by tools/annotate.mjs. Edit annotations through the local editor page, not by hand.\n'
    + 'window.__NOTES__ = [\n' + list.map(n => JSON.stringify(n) + ',\n').join('') + '];\n';
  const tmp = NOTES + '.tmp';
  await writeFile(tmp, body, 'utf8');
  await rename(tmp, NOTES);
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    let size = 0;
    const chunks = [];
    req.on('data', c => {
      size += c.length;
      if (size > MAX_BODY) { reject(new Error('body too large')); req.destroy(); return; }
      chunks.push(c);
    });
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    req.on('error', reject);
  });
}

const server = createServer(async (req, res) => {
  try {
    const url = new URL(req.url, 'http://x');
    const path = decodeURIComponent(url.pathname);
    if (path.endsWith('/api/notes')) {
      if (req.method !== 'POST') return send(res, 405, 'POST only');
      const list = cleanNotes(JSON.parse(await readBody(req)).notes);
      await saveNotes(list);
      console.log(`${new Date().toLocaleTimeString()}  saved ${list.length} notes`);
      return send(res, 200, JSON.stringify({ ok: true, count: list.length }), TYPES['.json']);
    }
    if (req.method !== 'GET' && req.method !== 'HEAD') return send(res, 405, 'method not allowed');
    if (path === '/edit' || path === '/edit/' || path === '/edit.html') return send(res, 200, await editPage(), TYPES['.html']);

    const file = normalize(join(ROOT, path === '/' ? 'index.html' : path));
    if (file !== ROOT && !file.startsWith(ROOT + sep)) return send(res, 403, 'forbidden');
    if (file.split(sep).includes('.git')) return send(res, 403, 'forbidden');
    const st = await stat(file).catch(() => null);
    if (!st?.isFile()) return send(res, 404, 'not found');
    send(res, 200, await readFile(file), TYPES[extname(file).toLowerCase()] || 'application/octet-stream');
  } catch (e) {
    send(res, e instanceof SyntaxError || /^bad |must be|too large/.test(e.message) ? 400 : 500, e.message);
  }
});
server.listen(PORT, HOST, () => console.log(`批注编辑页: http://${HOST}:${PORT}/edit   (浏览页: http://${HOST}:${PORT}/)`));
